export function translateError(error: unknown): string {
  const code =
    error && typeof error === 'object' && 'code' in error
      ? String(error.code)
      : undefined;
  if (code && (`errors.${code}` as TranslationKey) in enUS)
    return t(`errors.${code}` as TranslationKey);
  const message = error instanceof Error ? error.message : '';
  if (message === 'SCHEDULE_CONFLICT') return t('errors.scheduleConflict');
  return message || t('errors.requestFailed');
}

