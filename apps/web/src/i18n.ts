export type TranslationKey = keyof typeof enUS;
export const translations: Record<
  Locale,
  Readonly<Record<TranslationKey, string>>
> = { 'pt-BR': ptBR, 'en-US': enUS };

export const isLocale = (value: unknown): value is Locale =>
  typeof value === 'string' &&
  (SUPPORTED_LOCALES as readonly string[]).includes(value);

export function getLocale(): Locale {
  const persisted =
    typeof localStorage === 'undefined'
      ? null
      : localStorage.getItem(LOCALE_STORAGE_KEY);
  const locale = isLocale(persisted) ? persisted : DEFAULT_LOCALE;
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
  return locale;
}

export function setLocale(locale: Locale): void {
  if (!isLocale(locale))
    throw new Error(`Unsupported locale: ${String(locale)}`);
  localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
}

export function t(
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  if (
    key === 'settings.activeSummary' &&
    typeof params.active === 'number' &&
    typeof params.inactive === 'number'
  ) {
    return `${t(params.active === 1 ? 'settings.activeOne' : 'settings.activeMany', { count: params.active })} · ${t(params.inactive === 1 ? 'settings.inactiveOne' : 'settings.inactiveMany', { count: params.inactive })}`;
  }
  if (
    key === 'settings.courtSummary' &&
    typeof params.active === 'number' &&
    typeof params.archived === 'number'
  ) {
    return `${t(params.active === 1 ? 'settings.courtActiveOne' : 'settings.courtActiveMany', { count: params.active })} · ${t(params.archived === 1 ? 'settings.courtArchivedOne' : 'settings.courtArchivedMany', { count: params.archived })}`;
  }
  return Object.entries(params).reduce(
    (value, [name, replacement]) =>
      value.replaceAll(`{${name}}`, String(replacement)),
    translations[getLocale()][key],
  );
}

export function formatMoney(value: number, currency = 'BRL'): string {
  return new Intl.NumberFormat(getLocale(), {
    style: 'currency',
    currency,
  }).format(Number(value) || 0);
}

export function formatDate(value: string | Date, timeZone?: string): string {
  return new Intl.DateTimeFormat(getLocale(), {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    ...(timeZone ? { timeZone } : {}),
  }).format(new Date(value));
}

export function formatTime(value: string | Date, timeZone?: string): string {
  return new Intl.DateTimeFormat(getLocale(), {
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
    ...(timeZone ? { timeZone } : {}),
  }).format(new Date(value));
}

export function formatDateTime(
  value: string | Date,
  timeZone?: string,
): string {
  return `${formatDate(value, timeZone)} ${formatTime(value, timeZone)}`;
}

const label = (namespace: string, value: string | number): string => {
  const key = `${namespace}.${String(value)}` as TranslationKey;
  return key in enUS ? t(key) : String(value);
};
